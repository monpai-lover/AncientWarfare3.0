        public static string Focus(string pCardId)
        {
            string id = pCardId ?? "";
            if (id.StartsWith("qin_", StringComparison.Ordinal)) return "中央集权与战国统一";
            if (id.StartsWith("han_", StringComparison.Ordinal)) return "帝国扩张、制度建设与文治传统";
            if (id.StartsWith("three_", StringComparison.Ordinal)) return "三国竞争、军政联盟与地方整合";
            if (id.StartsWith("jin_", StringComparison.Ordinal)) return "门阀政治、统一与南北分裂";
            if (id.StartsWith("sui_", StringComparison.Ordinal)) return "统一战争、官僚制度与唐代国家基础";
            if (id.StartsWith("tang_", StringComparison.Ordinal)) return "唐代制度、边疆经营与盛衰转折";
            if (id.StartsWith("song_", StringComparison.Ordinal)) return "文官政治、财政改革与宋辽宋金关系";
            if (id.StartsWith("yuan_", StringComparison.Ordinal)) return "蒙古征服、多民族治理与帝国转型";
            if (id.StartsWith("ming_", StringComparison.Ordinal)) return "皇权国家、边防治理与财政改革";
            if (id.StartsWith("qing_", StringComparison.Ordinal)) return "八旗国家、边疆整合与近代转型";
            if (id.StartsWith("liao_", StringComparison.Ordinal)) return "契丹国家形成与北方多民族秩序";
            if (id.StartsWith("later_", StringComparison.Ordinal)) return "五代政权更替与藩镇军事政治";
            if (id.StartsWith("beiwei_", StringComparison.Ordinal) ||
                id.StartsWith("beiqi_", StringComparison.Ordinal) ||
                id.StartsWith("beizhou_", StringComparison.Ordinal))
                return "北朝政权整合与民族制度融合";
            return "政权更替、地方治理与个人政治选择";
        }

        public static string Detailed(string pCardId, string pName,
            string pDynasty, string pKingdom, string pBiography)
        {
            if (DetailedByCardId.TryGetValue(pCardId ?? "", out string curated))
                return curated;
            return HistoricalFigureCardBiographyCatalog.Build(
                pCardId, pName, pDynasty, pKingdom, pDynasty,
                HistoricalFigureCardCatalog.UnknownYear, pBiography, "", "",
                false);
        }

        public static string MinisterBiography(string pCardId, string pName,
            string pKingdom, string pEra, bool pMilitary, string pBiography)
        {
            if (DetailedByCardId.TryGetValue(pCardId ?? "", out string curated))
                return curated;
            string supplied = (pBiography ?? "").Trim();
            return HistoricalFigureCardBiographyCatalog.Build(
                pCardId, pName, pEra, pKingdom, pEra,
                HistoricalFigureCardCatalog.UnknownYear,
                supplied, "", "", pMilitary);
        }

        public static string MinisterBackground(string pCardId, string pName,
            string pKingdom, string pEra, bool pMilitary)
        {
            string role = pMilitary ? "武将" : "文臣";
            return pName + "是" + pEra + "时期" + pKingdom + "的重要" + role + "，其活动与" +
                Focus(pCardId) + "密切相关。";
        }

        public static string MinisterDetailed(string pCardId, string pName,
            string pKingdom, string pEra, bool pMilitary, string pBiography)
        {
            string biography = MinisterBiography(pCardId, pName, pKingdom,
                pEra, pMilitary, pBiography);
            if (!DetailedByCardId.ContainsKey(pCardId ?? ""))
                return biography;
            return biography + "部署后按" + (pMilitary ? "军事官员" : "文官") +
                "处理，历史身份仍以本卡所属的" + pKingdom + "政权和" + pEra + "时代为准。";
        }
