        public static bool HasSpecific(string pCardId)
        {
            return !string.IsNullOrEmpty(pCardId) &&
                FocusByCardId.ContainsKey(pCardId);
        }

        public static string Build(string pCardId, string pName,
            string pDynasty, string pKingdom, string pEra, int pYear,
            string pBiography, string pFather, string pMother,
            bool pMilitary)
        {
            string name = pName ?? "历史人物";
            string era = string.IsNullOrWhiteSpace(pEra) ? "相关时代" : pEra;
            string kingdom = string.IsNullOrWhiteSpace(pKingdom) ? "相关政权" : pKingdom;
            string focus;
            if (!FocusByCardId.TryGetValue(pCardId ?? "", out focus))
                focus = name + "在" + era + "的" +
                    (pMilitary ? "军事活动" : "政治、文化或行政活动") +
                    "见于相关正史、文集与编年材料，具体事迹需结合不同史料互证。";
            string year = pYear == HistoricalFigureCardCatalog.UnknownYear
                ? "活动年代存在记载差异" : "重要活动约在" + pYear + "年前后";
            string parents = string.IsNullOrWhiteSpace(pFather) &&
                             string.IsNullOrWhiteSpace(pMother)
                ? "现有卡片未保存其可靠父母信息"
                : "卡片所记录的父母为" +
                  (string.IsNullOrWhiteSpace(pFather) ? "史料未详" : pFather) +
                  "与" + (string.IsNullOrWhiteSpace(pMother) ? "史料未详" : pMother);
            string source = string.IsNullOrWhiteSpace(pBiography)
                ? "本条资料按人物所属时代、政权和传记材料整理"
                : pBiography.Trim();
            return name + "属于" + era + "的" + kingdom + "人物。" +
                source + "" + focus + "" + year + "。" + parents + "。" +
                "卡片部署后保留其历史国号、身份和人物关系，具体评价应以史料背景而非游戏数值为准。";
        }
